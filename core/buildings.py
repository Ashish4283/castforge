BUILDING_CATEGORIES = {
    "buildings": "Buildings",
    "arenas": "Arenas & venues",
    "landscapes": "Landscapes",
    "trees": "Trees",
    "vehicles": "Vehicles",
    "roads": "Roads",
    "street": "Street furniture",
}
FAMILY_DEFAULT_HEIGHTS = {
    "street": 2.5,
    "arena": 14.0,
    "garden": 0.2,
    "tree": 8.0,
    "vehicle": 2.0,
    "road": 0.2,
}


def describe_buildings():
    return [
        {"id": name, "family": design.get("family", "building"),
         "category": design.get("category", "buildings"),
         "category_title": BUILDING_CATEGORIES[design.get("category", "buildings")],
         "height": design.get("height", FAMILY_DEFAULT_HEIGHTS.get(design.get("family"), 0)),
         **{**design, "footprint": list(design["footprint"])}}
        for name, design in BUILDING_DESIGNS.items()
    ]


def default_asset_spec(template_id, name=None):
    design = BUILDING_DESIGNS[template_id]
    family = design.get("family", "building")
    width, depth = design["footprint"]
    height = design.get("height", FAMILY_DEFAULT_HEIGHTS.get(family, 0))
    return {
        "name": name or template_id,
        "template": template_id,
        "family": family,
        "category": design.get("category", "buildings"),
        "footprint": [width, depth],
        "floors": design["floors"],
        "size": [width, depth, height],
        "wall_color": design["wall_color"],
        "roof_color": design["roof_color"],
    }
